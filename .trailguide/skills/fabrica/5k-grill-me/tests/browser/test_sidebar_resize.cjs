const {chromium}=require('playwright');
const {spawn,spawnSync}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),script=path.join(root,'scripts/grill_ui.py');
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'grill-sidebar-'));let server,browser;
 try{
  const fixture=JSON.parse(fs.readFileSync(path.join(root,'examples/design-context.json')));
  fixture.nodes.push({id:'Q3',parentId:null,title:'An open question',question:'What else matters?',answer:null,dependsOn:[]});
  fs.writeFileSync(path.join(dir,'input.json'),JSON.stringify(fixture));
  const published=spawnSync('python3',[script,'publish','--session-dir',dir,'--snapshot',path.join(dir,'input.json'),'--expected-revision','0'],{encoding:'utf8'});assert.equal(published.status,0,published.stderr);
  fs.writeFileSync(path.join(dir,'connection.json'),JSON.stringify({provider:'codex',transport:'inbox'}));
  fs.writeFileSync(path.join(dir,'presence.json'),JSON.stringify({at:Date.now()/1000}));
  server=spawn('python3',[script,'serve','--session-dir',dir]);
  const url=await new Promise((resolve,reject)=>{let out='';server.stdout.on('data',c=>{out+=c;if(out.includes('\n'))resolve(JSON.parse(out.split('\n')[0]).url)});server.on('exit',c=>reject(Error('Server exited '+c)))});
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  const page=await browser.newPage({viewport:{width:1100,height:1000}});page.setDefaultTimeout(5000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const shot=async name=>{if(process.env.SIDEBAR_SHOTS)await page.screenshot({path:path.join(process.env.SIDEBAR_SHOTS,name+'.png')})};
  await page.goto(url);await page.locator('[data-node="Q2"]').click();
  const handle=page.getByRole('separator',{name:'Resize sidebar'}), panel=page.locator('#panel');
  const width=async()=>Math.round((await panel.boundingBox()).width);
  const drag=async delta=>{
    const b=await handle.boundingBox();
    await page.mouse.move(b.x+b.width/2,b.y+100);await page.mouse.down();
    await page.mouse.move(b.x+b.width/2+delta,b.y+100,{steps:10});await page.mouse.up();
  };
  assert.equal(await width(),370);await shot('default');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Write my own answer',exact:true}).click();
  await page.locator('#draft').fill('Keep this draft while resizing.');
  await drag(-250);assert.equal(await width(),620);
  assert.equal(await page.locator('#draft').inputValue(),'Keep this draft while resizing.');
  assert.equal(Math.round((await page.locator('#workspace').boundingBox()).width),820);
  await page.locator('#panel').evaluate(el=>el.scrollTop=60);
  const scroll=await panel.evaluate(el=>el.scrollTop);
  await drag(-30);assert.equal(await width(),650);assert.equal(await panel.evaluate(el=>el.scrollTop),scroll);
  await panel.evaluate(el=>el.scrollTop=0);await shot('wide');
  await page.emulateMedia({colorScheme:'dark'});await shot('dark');await page.emulateMedia({colorScheme:'light'});
  await handle.focus();await page.keyboard.press('ArrowRight');assert.equal(await width(),640);
  await page.keyboard.press('Shift+ArrowLeft');assert.equal(await width(),690);
  await page.keyboard.press('Home');assert.equal(await width(),320);
  await page.keyboard.press('End');assert.equal(await width(),960);
  await drag(2000);assert.equal(await width(),320);
  await drag(-2000);assert.equal(await width(),960);
  await handle.dblclick();assert.equal(await width(),370);
  await drag(-250);assert.equal(await width(),620);
  let b=await handle.boundingBox();await page.mouse.move(b.x+5,b.y+100);await page.mouse.down();await page.mouse.move(b.x-100,b.y+100);
  await page.keyboard.press('Escape');await page.mouse.up();assert.equal(await width(),620);assert(await panel.isVisible());
  b=await handle.boundingBox();await page.mouse.move(b.x+5,b.y+100);await page.mouse.down();await page.mouse.move(b.x-100,b.y+100);
  await handle.dispatchEvent('pointercancel');await page.mouse.up();assert.equal(await width(),620);
  assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('sidebar-resizing')),false);
  await page.reload();await page.locator('[data-node="Q2"]').click();assert.equal(await width(),620);
  assert.equal(await page.locator('#draft').inputValue(),'Keep this draft while resizing.');
  await page.setViewportSize({width:1000,height:1000});await handle.focus();await page.keyboard.press('End');assert.equal(await width(),680);await shot('narrow-canvas');
  const legend=await page.locator('.legend').boundingBox(), tools=await page.locator('.tools').boundingBox();
  assert(tools.y+tools.height<=legend.y,'Canvas zoom controls must not overlap the legend');
  await page.setViewportSize({width:375,height:812});assert(!(await handle.isVisible()));assert.equal(await width(),375);await shot('mobile');
  await page.setViewportSize({width:1440,height:1000});
  await page.waitForFunction(()=>document.querySelector('#sidebarResize').getAttribute('aria-valuenow')==='680');assert.equal(await width(),680);
  await page.locator('#artifactsButton').click();assert(await handle.isVisible());assert(!(await page.locator('#nextQuestion').isVisible()));
  await drag(-100);assert.equal(Math.round((await page.locator('#artifactsSidebar').boundingBox()).width),780);await shot('artifacts');
  await page.locator('#closeArtifacts').click();assert(!(await handle.isVisible()));
  assert.deepEqual(errors,[]);
  console.log('PASS sidebar drag, bounds, persistence, draft and scroll retention, keyboard, cancel, artifacts and mobile layout');
 }finally{await browser?.close();server?.kill();fs.rmSync(dir,{recursive:true,force:true})}
})().catch(e=>{console.error(e);process.exitCode=1});
