  await page.locator('#recommendationTab').click();await page.locator('#buildRecommendation').click();
  assert.equal(await page.locator('#draft').inputValue(),recommended+'\n\nMy own direction.');
  assert.equal(await page.locator('#customTab').getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('#draft').evaluate(el=>el===document.activeElement),true);
  await page.locator('#recommendationTab').click();await page.locator('#buildRecommendation').click();
  assert.equal(await page.locator('#draft').inputValue(),recommended+'\n\nMy own direction.','Building never duplicates or discards text');
  await page.setViewportSize({width:540,height:1000});await shot('extended-narrow');
