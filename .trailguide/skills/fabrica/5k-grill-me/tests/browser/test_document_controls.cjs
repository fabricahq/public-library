const {chromium}=require('playwright');
const {spawn,spawnSync}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),script=path.join(root,'scripts/grill_ui.py');
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'grill-document-controls-'));let server,browser;
 const cli=(...args)=>{const p=spawnSync('python3',[script,...args],{encoding:'utf8'});assert.equal(p.status,0,p.stderr);return JSON.parse(p.stdout)};
 try{
  cli('publish','--session-dir',dir,'--snapshot',path.join(root,'examples/design-context.json'),'--expected-revision','0');
  const file=path.join(dir,'opening-spec.md');
  const content='# Complete artifact opening\n\nA draft specification for review.\n\n'+Array.from({length:12},(_,i)=>'## Section '+(i+1)+'\n\nKeep the complete opening operation coherent. Preserve typed work, show the current document, and explain any change in availability. These decisions guide the specification without authorizing implementation.\n\n').join('');
  fs.writeFileSync(file,content);cli('artifact','--session-dir',dir,'--file',file,'--title','Opening specification');
  server=spawn('python3',[script,'serve','--session-dir',dir]);
  const url=await new Promise((resolve,reject)=>{let out='';server.stdout.on('data',c=>{out+=c;if(out.includes('\n'))resolve(JSON.parse(out.split('\n')[0]).url)});server.on('exit',c=>reject(Error('Server exited '+c)))});
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  const page=await browser.newPage({viewport:{width:1280,height:900}});page.setDefaultTimeout(5000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const shot=async name=>{if(process.env.DOCUMENT_SHOTS)await page.screenshot({path:path.join(process.env.DOCUMENT_SHOTS,name+'.png')})};
  await page.goto(url);await page.locator('#artifactsButton').click();
  await page.getByRole('button',{name:'Open opening-spec.md on canvas',exact:true}).click();
  await page.locator('#closeArtifacts').click();
  const win=page.locator('.artifact-window').filter({has:page.getByRole('button',{name:'opening-spec.md',exact:true})});await win.waitFor();
  if(process.env.DOCUMENT_BASELINE){await shot('before');return;}
  const zoomIn=win.getByRole('button',{name:'Zoom in document',exact:true}),zoomOut=win.getByRole('button',{name:'Zoom out document',exact:true}),reset=win.getByRole('button',{name:'Reset document zoom to 100%',exact:true});
  const max=()=>win.getByRole('button',{name:'Maximize document',exact:true});
  const canvasStyle=await page.locator('#artifactWorld').getAttribute('style');
  const initial=await win.boundingBox(),h1=win.locator('.artifact-body h1');
  const heading=await h1.boundingBox();
  await zoomIn.click();assert.equal(await reset.textContent(),'125%');
  assert(Math.abs((await h1.boundingBox()).height/heading.height-1.25)<.02);
  assert.deepEqual(await win.boundingBox(),initial);
  assert.equal(await page.locator('#artifactWorld').getAttribute('style'),canvasStyle);
  await zoomOut.click();assert.equal(await reset.textContent(),'100%');
  for(let i=0;i<8;i++)await zoomIn.click();assert(await zoomIn.isDisabled());
  await reset.click();for(let i=0;i<2;i++)await zoomOut.click();assert(await zoomOut.isDisabled());await reset.click();
  await zoomIn.click();await shot('window');
  await max().click();
  assert.deepEqual(await win.boundingBox(),{x:0,y:0,width:1280,height:900});
  assert.equal(await reset.textContent(),'125%');
  await win.getByRole('button',{name:'Section 6',exact:true}).click();
  const section=await win.locator('.artifact-body h2').filter({hasText:'Section 6'}).boundingBox(),body=await win.locator('.artifact-body').boundingBox();
  assert(Math.abs(section.y-body.y-20)<2,'TOC must account for document zoom');
  await page.keyboard.press('Escape');await page.waitForFunction(()=>!document.querySelector('#documentFullscreen').open);
  assert.deepEqual(await win.boundingBox(),initial);
  await max().click();
  const pinch=await win.evaluate(el=>{const e=new WheelEvent('wheel',{bubbles:true,cancelable:true,ctrlKey:true,deltaY:-20});el.querySelector('.artifact-body').dispatchEvent(e);return e.defaultPrevented});
  assert(pinch);assert.notEqual(await reset.textContent(),'125%');assert.equal(await page.locator('#artifactWorld').getAttribute('style'),canvasStyle);
  await reset.click();await win.getByRole('button',{name:'Source',exact:true}).click();await zoomIn.click();
  assert(await win.locator('.markdown-source').isVisible());
  assert(await win.locator('.artifact-body').evaluate(el=>{el.scrollLeft=200;return el.scrollLeft>0}),'Long source lines must remain reachable');
  await win.locator('.artifact-body').evaluate(el=>el.scrollLeft=0);await shot('source');
  await win.getByRole('button',{name:'Rendered',exact:true}).click();await reset.click();
  await page.setViewportSize({width:2048,height:1007});await win.locator('.artifact-body').evaluate(el=>el.scrollTop=0);await shot('maximized');
  await page.emulateMedia({colorScheme:'dark'});await shot('dark');await page.emulateMedia({colorScheme:'light'});
  await page.setViewportSize({width:375,height:812});await shot('mobile');
  assert(await zoomIn.isVisible());assert.equal(await win.locator('.artifact-toolbar').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await win.getByRole('button',{name:'Restore window size',exact:true}).click();
  await page.setViewportSize({width:1280,height:900});
  await max().click();await zoomIn.click();await win.getByRole('button',{name:'Minimize Opening specification',exact:true}).click();
  assert.equal(await page.locator('#documentFullscreen').getAttribute('open'),null);
  await win.getByRole('button',{name:'Restore Opening specification',exact:true}).click();
  await page.reload();await win.waitFor();assert.equal(await reset.textContent(),'125%');
  await page.locator('#artifactsButton').click();await page.getByRole('button',{name:'Open Constraints on canvas',exact:true}).click();await page.locator('#closeArtifacts').click();
  const constraints=page.locator('.artifact-window').filter({has:page.getByRole('button',{name:'Constraints',exact:true})});
  assert.equal(await constraints.getByRole('button',{name:'Reset document zoom to 100%'}).textContent(),'100%');
  await constraints.getByRole('button',{name:'Maximize document'}).click();await constraints.getByRole('button',{name:'Zoom in document'}).click();await shot('constraints');
  await constraints.getByRole('button',{name:'Remove document from canvas'}).click();
  assert.equal(await page.locator('#documentFullscreen').getAttribute('open'),null);
  assert.deepEqual(errors,[]);
  console.log('PASS document controls');
 }finally{await browser?.close();server?.kill();fs.rmSync(dir,{recursive:true,force:true})}
})().catch(e=>{console.error(e);process.exitCode=1});
