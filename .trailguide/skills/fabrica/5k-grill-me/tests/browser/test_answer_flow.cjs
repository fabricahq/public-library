// Optional E2E: Playwright + Chromium. Set CHROMIUM_EXECUTABLE_PATH if needed.
const {chromium}=require('playwright');
const {spawnSync,spawn}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),script=path.join(root,'scripts/grill_ui.py');
(async()=>{
 let browser,server;
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'grill-answer-flow-'));
 try {
  const publish=spawnSync('python3',[script,'publish','--session-dir',dir,'--snapshot',path.join(root,'examples/design-context.json'),'--expected-revision','0'],{encoding:'utf8'});
  assert.equal(publish.status,0,publish.stderr);
  server=spawn('python3',[script,'serve','--session-dir',dir]);
  const url=await new Promise((resolve,reject)=>{let output='';server.stdout.on('data',chunk=>{output+=chunk;if(output.includes('\n'))resolve(JSON.parse(output.split('\n')[0]).url);});server.on('exit',code=>reject(Error('Server exited: '+code)));});
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  const page=await browser.newPage({viewport:{width:1100,height:1000},permissions:['clipboard-read','clipboard-write']});
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const shot=async name=>{if(process.env.ANSWER_FLOW_SHOTS)await page.screenshot({path:path.join(process.env.ANSWER_FLOW_SHOTS,`answer-flow-${name}.png`)});};
  await page.goto(url);
  await page.locator('[data-node="Q1"]').click();
  const original=await page.locator('.answer-body').innerText();
  await shot('saved-desktop');
  await page.locator('#editAnswer').click();
  assert.equal(await page.locator('#draft').inputValue(),original);
  assert(await page.locator('#send').isDisabled());
  assert.equal(await page.locator('#copySavedReply').count(),0);
  await page.locator('#draft').fill('A revised response.');
  await shot('editing-desktop');
  await page.locator('#cancelAnswer').click();
  assert.equal(await page.locator('.answer-body').innerText(),original);
  await page.locator('#answerRecommendation summary').click();
  await shot('recommendation-desktop');
  await page.locator('#useRecommendation').click();
  const recommendation=await page.locator('.chosen-recommendation').evaluate(el=>Array.from(el.querySelectorAll('p'),p=>p.textContent).join('\n\n'));
  assert(recommendation.length>0 && recommendation!==original);
  assert.equal(await page.locator('#copySavedReply').count(),0);
  await page.locator('#cancelAnswer').click();
  assert.equal(await page.locator('.answer-body').innerText(),original, 'Viewing or filling recommendation never saves');
  await page.locator('#editAnswer').click();
  await page.locator('#draft').fill('Saved custom response.');
  await page.locator('#send').click();
  await page.locator('.answer-body').filter({hasText:'Saved custom response.'}).waitFor();
  await page.locator('#copySavedReply').click();
  const copied=await page.evaluate(()=>navigator.clipboard.readText());
  assert(copied.includes('Saved custom response.') && copied.includes('Question when drafted:'));
  await page.locator('#editAnswer').click();
  assert.equal(await page.locator('#draft').inputValue(),'Saved custom response.');
  await page.locator('#draft').fill('');
  assert(await page.locator('#send').isDisabled());
  await page.locator('#closePanel').click();
  await page.locator('[data-node="Q1"]').click();
  assert.equal(await page.locator('#draft').inputValue(),'','Closing the panel preserves even an empty draft');
  await page.reload();await page.locator('[data-node="Q1"]').click();
  await page.getByRole('button',{name:'Resume editing',exact:true}).click();
  assert.equal(await page.locator('#draft').inputValue(),'','Reload preserves empty edits for recovery');
  await page.locator('#cancelAnswer').click();
  await page.locator('#editAnswer').click();
  assert.equal(await page.locator('#draft').inputValue(),'Saved custom response.','Cancel discards unsaved changes');
  await page.locator('#cancelAnswer').click();
  await page.locator('#answerRecommendation summary').click();await page.locator('#useRecommendation').click();
  await page.locator('#send').click();
  await page.locator('.answer-origin').waitFor();
  assert.equal((await page.locator('.answer-body').innerText()).replace(/\n+/g,'\n'),recommendation.replace(/\n+/g,'\n'));
  await shot('recommended-saved-desktop');
  await page.setViewportSize({width:540,height:1000});
  await shot('saved-narrow');
  await page.locator('#editAnswer').click();
  await page.locator('#recommendationTab').click();
  assert(await page.locator('#send').isDisabled());
  await page.locator('#customTab').click();
  assert(!(await page.locator('#workspace').isVisible()));
  await shot('editing-narrow');
  await page.locator('#cancelAnswer').click();
  await page.getByText('More options',{exact:true}).click();
  await page.locator('#clearAnswer').click();
  await page.locator('#customTab').click();
  assert.equal(await page.locator('#draft').inputValue(),'');
  await page.locator('#closePanel').click();await page.locator('[data-node="Q2"]').click();
  await shot('unanswered-narrow');
  await page.locator('#customTab').click();
  assert.equal(await page.locator('#draft').inputValue(),'');
  assert.equal(await page.locator('#copySavedReply').count(),0);
  await page.locator('#recommendationTab').click();await page.locator('#buildRecommendation').click();
  assert((await page.locator('#draft').inputValue()).includes('Yes, when relevant.'));
  assert.deepEqual(errors,[]);
  console.log('PASS answer edit, cancel, recommendation fill/save, clipboard context, empty-draft recovery, clear and new answer');
 } finally {await browser?.close();server?.kill();fs.rmSync(dir,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1});
