// Isolated live transport E2E. Uses a deterministic agent receipt/publication, not a model.
const {chromium}=require('playwright');
const {spawnSync,spawn}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),script=path.join(root,'scripts/grill_ui.py');
(async()=>{
 let browser,server,listener;
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'grill-live-browser-'));
 const cli=(...args)=>{const p=spawnSync('python3',[script,...args],{encoding:'utf8'});assert.equal(p.status,0,p.stderr);return JSON.parse(p.stdout)};
 try {
  cli('publish','--session-dir',dir,'--snapshot',path.join(root,'examples/design-context.json'),'--expected-revision','0');
  fs.writeFileSync(path.join(dir,'connection.json'),JSON.stringify({provider:'codex',transport:'inbox'}));
  server=spawn('python3',[script,'serve','--session-dir',dir]);
  const url=await new Promise((resolve,reject)=>{let output='';server.stdout.on('data',chunk=>{output+=chunk;if(output.includes('\n'))resolve(JSON.parse(output.split('\n')[0]).url)});server.on('exit',code=>reject(Error('Server exited: '+code)))});
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
  const page=await browser.newPage({viewport:{width:1100,height:1000}});
  page.setDefaultTimeout(5000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const shot=async name=>{if(process.env.DELIVERY_SHOTS)await page.screenshot({path:path.join(process.env.DELIVERY_SHOTS,`delivery-${name}.png`)})};
  await page.goto(url);await page.locator('[data-node="Q2"]').click();
  await page.locator('#customTab').click();
  await page.locator('#draft').fill('Include only decision-relevant examples.\n\nPreserve the agreed scope, link each example to the decision it informs, and explain what would make us choose differently. Keep supporting details available without making the main answer harder to scan. Record any remaining uncertainty explicitly so the specifications do not turn assumptions into requirements.');await page.locator('#send').click();
  await page.locator('#copySavedReply').waitFor();
  await shot('offline');
  await page.locator('#reconnectHelp').click();
  const dialog=page.getByRole('dialog',{name:'Automatic answer delivery'});
  assert(await dialog.isVisible());
  assert((await page.locator('#deliveryHelpReason').innerText()).includes('not currently listening'));
  assert((await page.locator('#deliveryHelpStep').innerText()).includes('Codex'));
  await shot('help');
  await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin:new URL(url).origin});
  const before=JSON.parse(fs.readFileSync(path.join(dir,'state.json'))).events;
  await page.locator('#copyResumeMessage').click();await page.locator('#copyResumeMessage.copy-success').waitFor();
  const copied=await page.evaluate(()=>navigator.clipboard.readText());
  assert(copied.includes('Use the grill-me-ui skill')&&copied.includes(dir)&&copied.includes('do not duplicate'));
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(dir,'state.json'))).events,before,'Copying must not submit an answer or reconnect');
  await page.keyboard.press('Escape');assert(await dialog.isHidden());
  assert(await page.locator('#reconnectHelp').evaluate(el=>el===document.activeElement));
  await page.locator('.answer-delivery [data-delivery-help]').click();assert(await dialog.isVisible());await page.locator('#closeDeliveryHelp').click();
  await page.locator('#presence').click();await page.getByRole('button',{name:'How automatic delivery works'}).click();assert(await dialog.isVisible());
  fs.writeFileSync(path.join(dir,'presence.json'),JSON.stringify({at:Date.now()/1000}));
  await page.locator('#deliveryHelpReason').filter({hasText:'Automatic delivery is available now'}).waitFor();
  assert(await page.locator('#reconnectHelp').isHidden());assert(await page.locator('#copyResumeMessage').isHidden());assert(await page.locator('#deliveryHelpRecovery').isHidden());await shot('connected');
  fs.writeFileSync(path.join(dir,'presence.json'),JSON.stringify({at:0}));
  fs.writeFileSync(path.join(dir,'connection.json'),JSON.stringify({provider:'claude',transport:'inbox'}));
  await page.locator('#deliveryHelpStep').filter({hasText:'Claude'}).waitFor();
  await page.locator('#deliveryHelpReason').filter({hasText:'not currently listening'}).waitFor();
  await page.setViewportSize({width:375,height:812});await shot('mobile');
  const box=await dialog.boundingBox();assert(box.x>=0&&box.x+box.width<=375);
  await page.emulateMedia({colorScheme:'dark'});await shot('dark');await page.emulateMedia({colorScheme:'light'});
  await page.setViewportSize({width:1100,height:1000});
  await page.route('**/state',route=>route.abort());await page.evaluate(()=>refresh());
  await page.locator('#deliveryHelpReason').filter({hasText:'lost contact'}).waitFor();await shot('server-offline');
  await page.unroute('**/state');
  fs.writeFileSync(path.join(dir,'connection.json'),JSON.stringify({provider:'codex',transport:'codex-queue'}));
  await page.locator('#deliveryHelpReason').filter({hasText:'Automatic delivery is available now'}).waitFor();
  await page.route('**/state',async route=>{const response=await route.fetch();const data=await response.json();data.pending[0].delivery={status:'unknown'};await route.fulfill({response,json:data});});
  await page.evaluate(()=>refresh());await page.locator('#deliveryHelpReason').filter({hasText:'delivery is unconfirmed'}).waitFor();await shot('unconfirmed');
  await page.unroute('**/state');
  await page.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(Error('Denied'))},configurable:true}));
  const standalone=path.join(dir,'standalone.html');cli('render','--snapshot',path.join(root,'examples/design-context.json'),'--output',standalone);
  await page.goto('file://'+standalone);await page.locator('#presence').click();await page.getByRole('button',{name:'How automatic delivery works'}).click();
  assert((await page.locator('#deliveryHelpReason').innerText()).includes('standalone copy'));assert((await page.locator('#deliveryHelpOutcome').innerText()).includes('this standalone copy will remain'));await shot('standalone');
  await page.locator('#copyResumeMessage').click();await page.locator('#copyDialog').waitFor();
  assert((await page.locator('#copyText').inputValue()).includes('\"session\"'));
  await page.locator('#closeDialog').click();assert(await dialog.isVisible());
  assert.deepEqual(errors,[]);
  console.log('PASS reconnect help, exact session copy, no submissions, live recovery, Claude, offline, standalone and clipboard fallback');
 } finally {await browser?.close();listener?.kill();server?.kill();fs.rmSync(dir,{recursive:true,force:true})}
})().catch(error=>{console.error(error);process.exitCode=1});
