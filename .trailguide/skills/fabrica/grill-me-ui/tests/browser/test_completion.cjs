  await page.emulateMedia({colorScheme:'dark'});await shot('waiting-dark');
  await page.emulateMedia({reducedMotion:'reduce'});assert.equal(await pulse.evaluate(el=>getComputedStyle(el).animationName),'none');await shot('waiting-reduced-motion');
