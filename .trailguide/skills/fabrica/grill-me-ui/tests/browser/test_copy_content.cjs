// Clipboard E2E uses an isolated interview and never submits an answer.
const {chromium}=require('playwright');
const {spawnSync,spawn}=require('node:child_process');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const shots=process.env.COPY_SHOTS;
if(shots)fs.mkdirSync(shots,{recursive:true});
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'grill-copy-'));let server,browser;
 try {
 const sample=JSON.parse(fs.readFileSync(path.join(root,'examples/design-context.json')));
 Object.assign(sample.nodes[1],{title:'Reference import boundary',question:'Should automatic reference inclusion allow linked regular files anywhere within the same source repository at its recorded revision, including shared documents outside a skill folder, while refusing links that escape that repository or require guessing another source?',agentRecommendationSummary:'Yes. Use the recorded source repository as the boundary.',agentRecommendation:'Follow links transitively within that immutable source revision. Retain existing import size limits and refusals for unsupported file types such as symbolic links. If the boundary or a limit is exceeded, explain the offending reference chain and fail instead of installing a partial result.'});
 fs.writeFileSync(path.join(dir,'sample.json'),JSON.stringify(sample));
 const publish=spawnSync('python3',[path.join(root,'scripts/grill_ui.py'),'publish','--session-dir',dir,'--snapshot',path.join(dir,'sample.json'),'--expected-revision','0'],{encoding:'utf8'});assert.equal(publish.status,0,publish.stderr);
 server=spawn('python3',[path.join(root,'scripts/grill_ui.py'),'serve','--session-dir',dir]);
 const url=await new Promise((resolve,reject)=>{let text='';server.stdout.on('data',c=>{text+=c;if(text.includes('\n'))resolve(JSON.parse(text.split('\n')[0]).url)});server.on('exit',c=>reject(Error('Server exited '+c)))});
 browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const shot=async name=>{if(shots)await page.screenshot({path:path.join(shots,name+'.png')})};
 page.setDefaultTimeout(5000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);await page.locator('[data-node="Q2"]').click();
 await page.evaluate(()=>{document.documentElement.style.setProperty('--sidebar-width','760px')});
 await page.locator('#fit').click();
 const questionBounds=await page.locator('.question-details').boundingBox(), questionCopyBounds=await page.locator('#copyQuestion').boundingBox();
 assert(questionCopyBounds.y>=questionBounds.y+questionBounds.height,'Question copy action follows the full question');
 const recommendationBounds=await page.locator('.chosen-recommendation > p').last().boundingBox(), recommendationCopyBounds=await page.locator('#copyRecommendation').boundingBox();
 assert(recommendationCopyBounds.y>=recommendationBounds.y+recommendationBounds.height,'Recommendation copy action follows its explanation');
 await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin:new URL(url).origin});
 await page.getByRole('button',{name:'Copy full question',exact:true}).focus();
 await page.keyboard.press('Enter');
 await page.locator('#copyQuestion.copy-success').waitFor();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),sample.nodes[1].question);
 await page.getByRole('button',{name:'Copy full recommendation',exact:true}).click();
 await page.locator('#copyRecommendation.copy-success').waitFor();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),sample.nodes[1].agentRecommendationSummary+'\n\n'+sample.nodes[1].agentRecommendation);
 await shot('copied');
 await page.waitForFunction(()=>!document.querySelector('.copy-success'));
 await shot('desktop');
 await page.emulateMedia({colorScheme:'dark'});await page.evaluate(()=>document.documentElement.style.setProperty('--sidebar-width','425px'));await page.locator('#fit').click();await shot('reference-dark');
 await page.emulateMedia({colorScheme:'light'});await page.evaluate(()=>document.documentElement.style.setProperty('--sidebar-width','760px'));await page.locator('#fit').click();
 await page.locator('#customTab').click();await page.locator('#draft').fill('Keep my draft');
 await page.getByRole('button',{name:'Copy full question',exact:true}).click();
 assert.equal(await page.locator('#draft').inputValue(),'Keep my draft');
 await page.locator('#recommendationTab').click();
 await page.getByRole('button',{name:'Copy full recommendation',exact:true}).click();
 await page.locator('#customTab').click();assert.equal(await page.locator('#draft').inputValue(),'Keep my draft');
 await page.locator('#recommendationTab').click();
 await page.setViewportSize({width:375,height:900});await shot('mobile');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.emulateMedia({colorScheme:'dark'});await shot('mobile-dark');
 await page.emulateMedia({colorScheme:'light'});await page.setViewportSize({width:1440,height:1080});
 await page.evaluate(()=>{navigator.clipboard.writeText=()=>Promise.reject(Error('Denied'))});
 await page.getByRole('button',{name:'Copy full recommendation',exact:true}).click();
 await page.getByRole('dialog',{name:'Copy full recommendation'}).waitFor();
 assert.equal(await page.locator('#copyText').inputValue(),sample.nodes[1].agentRecommendationSummary+'\n\n'+sample.nodes[1].agentRecommendation);
 await shot('fallback');
 await page.keyboard.press('Escape');
 await page.locator('[data-node="Q1"]').click();await page.locator('#answerRecommendation').evaluate(e=>e.open=true);
 await page.getByRole('button',{name:'Copy full recommendation',exact:true}).click();
 await page.getByRole('dialog',{name:'Copy full recommendation'}).waitFor();
 assert.equal(await page.locator('#copyText').inputValue(),sample.nodes[0].agentRecommendationSummary+'\n\n'+sample.nodes[0].agentRecommendation);
 assert.deepEqual(errors,[]);console.log('PASS exact clipboard contents, draft preservation, saved-answer recommendation, responsive layout and clipboard fallback');
 } finally {await browser?.close();server?.kill();fs.rmSync(dir,{recursive:true,force:true})}
})().catch(e=>{console.error(e);process.exitCode=1});
