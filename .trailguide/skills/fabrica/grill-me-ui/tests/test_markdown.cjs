const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../assets/canvas.html'), 'utf8');
const start = source.indexOf('      function documentMarkup(');
const end = source.indexOf('      // View preferences contain only placement', start);
const esc = s => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const render = new Function('esc', source.slice(start,end) + '; return documentMarkup;')(esc);
assert.equal(render('# Glossary\n\n**Term**:\nMeaning'), '<h1 data-document-line="0" tabindex="-1">Glossary</h1><p data-document-line="2" tabindex="-1"><strong>Term</strong>:<br>Meaning</p>');
assert.equal(render('`**literal**`'), '<p><code>**literal**</code></p>');
const unsafe = '<img src=x onerror=alert(1)>\n<script>alert(1)</script>';
assert(!render(unsafe).includes('<img'));
assert(!render(unsafe).includes('<script'));
assert(render(unsafe).includes('&lt;script&gt;'));
assert.equal(render('```html\n<script>x</script>\n```'), '<pre><code>&lt;script&gt;x&lt;/script&gt;</code></pre>');
console.log('PASS glossary formatting, literal code, escaped HTML');

const outline=[];
const text='# Same\n\n## Same\n\n**Term**:\nDefinition\n\n~~~~md\n# Not a heading\n**Not a term**:\n~~~~\n\nUnderlined\n----------\n\n### C#\n';
const html=render(text,outline);
assert.deepEqual(outline,[{line:0,level:1,title:'Same'},{line:2,level:2,title:'Same'},{line:4,level:3,title:'Term'},{line:12,level:2,title:'Underlined'},{line:15,level:3,title:'C#'}]);
for(const entry of outline) assert(html.includes(`data-document-line="${entry.line}"`));
const more=[];render('# **Title** and `code` ###\n\nInline **bold**: not a glossary term\n\n```\n# code',more);
assert.deepEqual(more,[{line:0,level:1,title:'Title and code'}]);
const empty=[];render('Plain text without headings',empty);assert.deepEqual(empty,[]);
console.log('PASS unique line targets, nested and duplicate headings, glossary terms, setext headings and excluded code');

const table = render('| State | What the user sees | Writes |\n| :--- | :---: | ---: |\n| Ready | **Document** and `code` | 42 |\n| Waiting | Loading |');
assert(table.includes('<table><thead><tr><th scope="col" style="text-align:left">State</th>'));
assert(table.includes('<th scope="col" style="text-align:center">What the user sees</th>'));
assert(table.includes('<td style="text-align:right">42</td>'));
assert(table.includes('<strong>Document</strong> and <code>code</code>'));
assert(table.includes('<td style="text-align:right"></td>'));
assert(render('A | B\n--- | ---\nx | y | ignored').includes('<td style="text-align:left">y</td></tr>'));
assert(!render('A | B\n--- | ---\nx | y | ignored').includes('ignored'));
assert(render('| A | B |\n| --- | --- |\n| one \\| two | `x\\|y` |').includes('one | two</td><td style="text-align:left"><code>x|y</code>'));
assert(render('| Only |\n| --- |').includes('<tbody></tbody>'));
assert(!render('A | B\n--- | --- | ---\nx | y').includes('<table>'));
assert(!render('A | B\nmaybe | separator\nx | y').includes('<table>'));
assert(!render('```md\nA | B\n--- | ---\nx | y\n```').includes('<table>'));
assert(!render('A | B\n--- | ---\n<script>x</script> | <img src=x>').includes('<script>'));
const tableOutline=[];
const followed=render('A | B\n--- | ---\nx | y\n\n## After\nParagraph',tableOutline);
assert(followed.includes('</table></div><h2 data-document-line="4"'));
assert.deepEqual(tableOutline,[{line:4,level:2,title:'After'}]);
assert(render('A | B\n--- | ---\nx | y\n```\ncode | literal\n```').includes('</table></div><pre><code>code | literal</code></pre>'));
console.log('PASS table alignment, formatting, escaped pipes, missing/extra cells, invalid syntax, code fences, safe HTML and following blocks');
